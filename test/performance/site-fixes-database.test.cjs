'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const test = require('node:test');
const ts = require('typescript');

const { createIndexSql } = require('../../lib/performance/db/checks.cjs');
const builders = require('../../lib/performance/site-fixes/database.cjs');

const now = new Date(Date.UTC(2026, 10, 20, 9, 30, 5));
const orders = { schema: 'public', name: 'orders' };
const createIndex = createIndexSql(orders, ['store_id']);
const dropIndex = 'DROP INDEX CONCURRENTLY "public"."orders_old_idx";';

function project(context, files = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bpc-db-fix-'));
  context.after(() => fs.rmSync(root, { recursive: true, force: true }));
  for (const [name, contents] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, name)), { recursive: true });
    fs.writeFileSync(path.join(root, name), contents);
  }
  return root;
}

function build(root, finding) {
  return builders[finding.ruleId]({ finding, root, now });
}

function onlyTarget(result) {
  assert.equal(result.targets.length, 1);
  const [target] = result.targets;
  assert.equal(target.create, true);
  return target;
}

function assertParses(file, text) {
  const parsed = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, false);
  assert.equal(parsed.parseDiagnostics.length, 0, text);
}

const foreignKeyFinding = {
  target: 'public.orders',
  ruleId: 'db-unindexed-foreign-key',
  message: '...',
  suggestion: createIndex,
};

test('writes a Prisma migration folder holding only the concurrent build', (context) => {
  const root = project(context, { 'prisma/migrations/migration_lock.toml': 'provider = "postgresql"\n' });
  const result = build(root, foreignKeyFinding);
  const target = onlyTarget(result);
  assert.equal(target.file, path.join(root, 'prisma/migrations/20261120093005_add_orders_store_id_idx/migration.sql'));
  assert.equal(
    target.text,
    '-- db-unindexed-foreign-key: generated by loadwise perf\nCREATE INDEX CONCURRENTLY "orders_store_id_idx" ON "public"."orders" ("store_id");\n',
  );
  assert.match(result.note, /@@index\(\[\.\.\.\], map: "orders_store_id_idx"\)/);
});

test('writes a TypeORM migration class with transaction = false and a down()', (context) => {
  const root = project(context, {
    'src/migrations/1700000000000-Init.ts': "import { MigrationInterface, QueryRunner } from 'typeorm';\n",
  });
  const result = build(root, { ...foreignKeyFinding, ruleId: 'db-missing-index' });
  const target = onlyTarget(result);
  assert.equal(target.file, path.join(root, `src/migrations/${now.getTime()}-AddOrdersStoreIdIdx.ts`));
  assert.match(target.text, /export class AddOrdersStoreIdIdx\d+ implements MigrationInterface \{\n {2}name = /);
  assert.match(target.text, /\n {2}transaction = false;\n/);
  assert.match(
    target.text,
    /await queryRunner\.query\(`CREATE INDEX CONCURRENTLY "orders_store_id_idx" ON "public"\."orders" \("store_id"\)`\);/,
  );
  assert.match(
    target.text,
    /await queryRunner\.query\(`DROP INDEX CONCURRENTLY IF EXISTS "public"\."orders_store_id_idx"`\);/,
  );
  assert.match(result.note, /migrationsTransactionMode/);
  assertParses(target.file, target.text);
});

test('writes a CommonJS Knex migration that opts out of the transaction', (context) => {
  const root = project(context, {
    'knexfile.js': "module.exports = { client: 'pg', migrations: { directory: './db/migrations' } };\n",
    'db/migrations/20240101000000_init.js': 'exports.up = function (knex) {};\n',
  });
  const target = onlyTarget(build(root, foreignKeyFinding));
  assert.equal(target.file, path.join(root, 'db/migrations/20261120093005_add_orders_store_id_idx.js'));
  assert.ok(
    target.text.startsWith('exports.config = { transaction: false };\n\nexports.up = async function (knex) {\n'),
  );
  assertParses(target.file, target.text);
});

test('writes a Sequelize migration', (context) => {
  const root = project(context, { '.sequelizerc': "module.exports = { 'migrations-path': 'database/migrations' };\n" });
  const target = onlyTarget(build(root, foreignKeyFinding));
  assert.equal(target.file, path.join(root, 'database/migrations/20261120093005-add-orders-store-id-idx.js'));
  assert.match(target.text, /await queryInterface\.sequelize\.query\(`CREATE INDEX CONCURRENTLY/);
  assertParses(target.file, target.text);
});

test('continues Flyway and golang-migrate numbering', (context) => {
  const flyway = project(context, { 'db/migrations/V7__init.sql': 'SELECT 1;\n' });
  assert.equal(
    onlyTarget(build(flyway, foreignKeyFinding)).file,
    path.join(flyway, 'db/migrations/V8__add_orders_store_id_idx.sql'),
  );
  const golang = project(context, { 'migrations/000003_init.up.sql': 'SELECT 1;\n' });
  const result = build(golang, foreignKeyFinding);
  assert.deepEqual(
    result.targets.map((target) => [path.basename(target.file), target.text]),
    [
      ['000004_add_orders_store_id_idx.up.sql', createIndex + '\n'],
      [
        '000004_add_orders_store_id_idx.down.sql',
        'DROP INDEX CONCURRENTLY IF EXISTS "public"."orders_store_id_idx";\n',
      ],
    ],
  );
});

test('falls back to a plain SQL file and says how to run it', (context) => {
  const root = project(context);
  const result = build(root, { ...foreignKeyFinding, ruleId: 'db-slow-query-plan' });
  assert.equal(onlyTarget(result).file, path.join(root, 'migrations/20261120093005_add_orders_store_id_idx.sql'));
  assert.match(result.note, /No migration tool was detected.*outside a transaction/);
  assert.match(result.note, /Unvalidated/);
});

test('has no fix when HypoPG showed the index does not help', (context) => {
  const root = project(context);
  const message = 'This query plans a sequential scan... A hypothetical `x` did not change the plan (HypoPG), so ...';
  assert.equal(build(root, { ...foreignKeyFinding, ruleId: 'db-slow-query-plan', message }), undefined);
});

test('drops an unused index and leaves the restore step to the saved definition', (context) => {
  const root = project(context, { 'prisma/migrations/migration_lock.toml': '' });
  const result = build(root, {
    target: 'public.orders',
    ruleId: 'db-unused-index',
    message: '...',
    suggestion: dropIndex,
  });
  const target = onlyTarget(result);
  assert.match(target.file, /20261120093005_drop_orders_old_idx[\\/]migration\.sql$/);
  assert.match(target.text, /\nDROP INDEX CONCURRENTLY "public"\."orders_old_idx";\n$/);
  assert.match(result.note, /remove the matching `@@index`/);
});

test('writes a TypeORM down() that says how to restore a dropped index', (context) => {
  const root = project(context, { 'src/migrations/1-Init.ts': 'export class Init implements MigrationInterface {}\n' });
  const target = onlyTarget(
    build(root, { target: 'public.orders', ruleId: 'db-duplicate-index', suggestion: dropIndex }),
  );
  assert.match(target.text, /\/\/ Recreate the index .*pg_get_indexdef\('"public"\."orders_old_idx"'::regclass\)/);
  assertParses(target.file, target.text);
});

test('drops a MySQL index online', (context) => {
  const root = project(context);
  const suggestion = 'ALTER TABLE `orders` DROP INDEX `orders_old_idx`, ALGORITHM=INPLACE, LOCK=NONE;';
  const result = build(root, { target: 'shop.orders', ruleId: 'db-unused-index', suggestion });
  assert.match(
    onlyTarget(result).text,
    /\nALTER TABLE `orders` DROP INDEX `orders_old_idx`, ALGORITHM=INPLACE, LOCK=NONE;\n$/,
  );
  assert.doesNotMatch(result.note, /outside a transaction/);
});

test('writes a migrate-mongo migration whose down() recreates the index', (context) => {
  const root = project(context, {
    'migrate-mongo-config.js': "module.exports = { migrationsDir: 'mongo-migrations' };\n",
  });
  const finding = {
    target: 'shop.orders',
    ruleId: 'db-unused-index',
    message: 'Index `status_1` `{"status":1}` on `orders` had 0 accesses',
    suggestion: 'db.getCollection("orders").dropIndex("status_1")',
  };
  const target = onlyTarget(build(root, finding));
  assert.equal(target.file, path.join(root, 'mongo-migrations/20261120093005-drop-status-1.js'));
  assert.match(target.text, /await db\.collection\("orders"\)\.dropIndex\("status_1"\);/);
  assert.match(target.text, /await db\.collection\("orders"\)\.createIndex\(\{"status":1\}, \{ name: "status_1" \}\);/);
  assertParses(target.file, target.text);
});

test('writes a mongosh script without migrate-mongo', (context) => {
  const root = project(context);
  const finding = {
    target: 'shop.orders',
    ruleId: 'db-duplicate-index',
    suggestion: 'db.getCollection("orders").dropIndex("a_1")',
  };
  const result = build(root, finding);
  assert.equal(onlyTarget(result).text, 'db.getCollection("orders").dropIndex("a_1");\n');
  assert.match(result.note, /mongosh/);
});

