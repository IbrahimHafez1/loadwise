const fs = require('node:fs');
const path = require('node:path');
const { syntax: ts } = require('./compiler.cjs');
const { findPrismaSchemaFiles } = require('./schema/prisma-schema.cjs');
const {
  awaitedResult,
  chainedMethod,
  clientSideQuery,
  consumesLazyQuery,
  firstElementRead,
  isDiscardedValue,
  outsideWrappers,
} = require('./query-results.cjs');
const { findRepeatOwner } = require('./repeated.cjs');
const { shouldReportLoopQuery } = require('./query-loops.cjs');
const { isSequentialByDesign } = require('./sequential-loops.cjs');

const READ_OPERATIONS = new Set([
  'findUnique',
  'findUniqueOrThrow',
  'findFirst',
  'findFirstOrThrow',
  'findMany',
  'count',
  'aggregate',
  'groupBy',
]);
const SINGLE_ROW_WRITES = new Set(['create', 'update', 'delete', 'upsert']);
const RAW_TEMPLATE_TAGS = new Set(['$queryRaw', '$executeRaw']);
const promiseMethods = new Set(['then', 'catch', 'finally']);
const COUNT_OPTIONS = new Set(['where']);
const ZERO_COMPARISONS = new Set([
  ts.SyntaxKind.EqualsEqualsEqualsToken,
  ts.SyntaxKind.ExclamationEqualsEqualsToken,
  ts.SyntaxKind.EqualsEqualsToken,
  ts.SyntaxKind.ExclamationEqualsToken,
]);
const EXISTENCE_THRESHOLDS = new Map([
  [ts.SyntaxKind.GreaterThanToken, { left: 0, right: 1 }],
  [ts.SyntaxKind.LessThanEqualsToken, { left: 0, right: 1 }],
  [ts.SyntaxKind.GreaterThanEqualsToken, { left: 1, right: 0 }],
  [ts.SyntaxKind.LessThanToken, { left: 1, right: 0 }],
]);
const FIRST_OPTIONS = new Set(['where', 'orderBy', 'select', 'include', 'omit']);
const FILTER_SORT_OPTIONS = new Set(['where', 'orderBy', 'select']);
const PRISMA_PACKAGE_PATH = /\/node_modules\/(?:@prisma\/client|\.prisma\/client)\//;
const generatedFiles = new WeakMap();
const DELEGATE_OPERATIONS = new Set([
  ...READ_OPERATIONS,
  ...SINGLE_ROW_WRITES,
  'createMany',
  'createManyAndReturn',
  'updateMany',
  'updateManyAndReturn',
  'deleteMany',
]);
const SCHEMA_MODEL_BLOCK = /^[ \t]*(?:model|view)[ \t]+(\w+)[ \t]*\{/gm;
const CLIENT_RECEIVER_NAME = /prisma|^(?:tx|trx|db|transaction)$/i;
const delegatesByDirectory = new Map();
const delegatesByOwner = new Map();
const packagesByRepository = new Map();

function isGeneratedPrismaFile(file) {
  if (!generatedFiles.has(file)) {
    // The modern generator emits each model into the application's own directory.
    const fromPackage = PRISMA_PACKAGE_PATH.test(file.fileName.replaceAll('\\', '/'));
    const fromGenerator =
      !fromPackage &&
      file.statements.length > 0 &&
      file.text.slice(0, file.statements[0].getStart(file)).includes('This is code generated by Prisma') &&
      file.statements.some(
        (statement) =>
          ts.isImportDeclaration(statement) &&
          ts.isStringLiteral(statement.moduleSpecifier) &&
          statement.moduleSpecifier.text.startsWith('@prisma/client/runtime/'),
      );
    generatedFiles.set(file, fromPackage || fromGenerator);
  }
  return generatedFiles.get(file);
}

function consumesPrismaQuery(call, checker) {
  return consumesLazyQuery(call, checker) || promiseMethods.has(chainedMethod(call)?.expression.name.text);
}

function delegateName(owner) {
  if (
    ts.isInterfaceDeclaration(owner) &&
    owner.name.text.endsWith('Delegate') &&
    isGeneratedPrismaFile(owner.getSourceFile())
  ) {
    return owner.name.text.slice(0, -'Delegate'.length);
  }
}

function readText(filename) {
  try {
    return fs.readFileSync(filename, 'utf8');
  } catch {
    return undefined;
  }
}

function hasManifest(directory) {
  return fs.existsSync(path.join(directory, 'package.json'));
}

function isRepositoryRoot(directory) {
  return fs.existsSync(path.join(directory, '.git')) || fs.existsSync(path.join(directory, 'pnpm-workspace.yaml'));
}

function childDirectories(directory) {
  try {
    return fs
      .readdirSync(directory, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && entry.name !== 'node_modules' && !entry.name.startsWith('.'))
      .map((entry) => path.join(directory, entry.name));
  } catch {
    return [];
  }
}

// The packages whose schema may define the client a file uses: the file's own package and its ancestors, and in a
// repository every package up to two levels down (`packages/prisma`, `apps/api`), where a client wrapper lives.
function schemaOwnerDirectories(sourceDirectory) {
  const owners = new Set();
  let repositoryRoot;
  for (let current = sourceDirectory; ; current = path.dirname(current)) {
    if (hasManifest(current)) owners.add(current);
    if (isRepositoryRoot(current)) {
      repositoryRoot = current;
      break;
    }
    if (path.dirname(current) === current) break;
  }
  for (const workspacePackage of repositoryRoot ? repositoryPackages(repositoryRoot) : []) owners.add(workspacePackage);
  return owners;
}

function repositoryPackages(repositoryRoot) {
  if (!packagesByRepository.has(repositoryRoot)) {
    const packageLevel = childDirectories(repositoryRoot);
    const candidates = [...packageLevel, ...packageLevel.flatMap(childDirectories)];
    packagesByRepository.set(repositoryRoot, candidates.filter(hasManifest));
  }
  return packagesByRepository.get(repositoryRoot);
}

function ownerDelegates(owner) {
  if (!delegatesByOwner.has(owner)) {
    const delegates = new Map();
    for (const schemaFile of findPrismaSchemaFiles(owner)) {
      for (const [, modelName] of (readText(schemaFile) ?? '').matchAll(SCHEMA_MODEL_BLOCK)) {
        delegates.set(modelName[0].toLowerCase() + modelName.slice(1), modelName);
      }
    }
    delegatesByOwner.set(owner, delegates);
  }
  return delegatesByOwner.get(owner);
}

// Maps each client delegate property (`eventType`) to its model name (`EventType`).
function schemaDelegates(sourceFile) {
  const sourceDirectory = path.dirname(path.resolve(sourceFile.fileName));
  if (!delegatesByDirectory.has(sourceDirectory)) {
    const delegates = new Map();
    for (const owner of schemaOwnerDirectories(sourceDirectory)) {
      for (const [delegate, modelName] of ownerDelegates(owner)) delegates.set(delegate, modelName);
    }
    delegatesByDirectory.set(sourceDirectory, delegates);
  }
  return delegatesByDirectory.get(sourceDirectory);
}

// Without a generated client `prisma.user.findMany` resolves to nothing. A receiver named like a client whose
// delegate property is unknown to the checker and matches a schema model is taken as Prisma, at lower precision.
function modelNameFromSchema(methodName, checker) {
  const access = methodName.parent;
  if (
    !DELEGATE_OPERATIONS.has(methodName.text) ||
    !ts.isPropertyAccessExpression(access) ||
    access.name !== methodName
  ) {
    return;
  }
  const delegate = access.expression;
  if (!ts.isPropertyAccessExpression(delegate) || checker.getSymbolAtLocation(delegate.name)) return;
  const client = delegate.expression;
  const clientName = ts.isIdentifier(client) ? client.text : ts.isPropertyAccessExpression(client) && client.name.text;
  if (!clientName || !CLIENT_RECEIVER_NAME.test(clientName)) return;
  return schemaDelegates(methodName.getSourceFile()).get(delegate.name.text);
}

function prismaModelName(methodName, checker) {
  const declarations = checker.getSymbolAtLocation(methodName)?.declarations;
  if (!declarations?.length) return modelNameFromSchema(methodName, checker);
  if (declarations?.length && declarations.every((declaration) => declaration.parent === declarations[0].parent)) {
    return delegateName(declarations[0].parent);
  }
}

function prismaModelNameFromReceiver(receiver, checker) {
  const declarations = checker.getTypeAtLocation(receiver).getSymbol()?.declarations;
  if (declarations?.length === 1) return delegateName(declarations[0]);
}

function readsResultLength(awaited) {
  const receiver = outsideWrappers(awaited);
  const access = receiver.parent;
  return (
    ts.isPropertyAccessExpression(access) &&
    access.expression === receiver &&
    access.name.text === 'length' &&
    !ts.isAssignmentTarget(access) &&
    !ts.isDeleteExpression(outsideWrappers(access).parent) &&
    !isDiscardedValue(access)
  );
}

function hasOnlyOptions(call, allowed) {
  if (call.arguments.length === 0) return true;
  const [options] = call.arguments;
  return (
    call.arguments.length === 1 &&
    ts.isObjectLiteralExpression(options) &&
    options.properties.every(
      (property) =>
        (ts.isPropertyAssignment(property) || ts.isShorthandPropertyAssignment(property)) &&
        (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
        allowed.has(property.name.text),
    )
  );
}

function countForExistence(call) {
  if (ts.isOptionalChain(call)) return false;
  const awaited = awaitedResult(call);
  if (!awaited) return false;
  const count = outsideWrappers(awaited);
  const comparison = count.parent;
  if (!ts.isBinaryExpression(comparison)) return false;

  const countOnLeft = comparison.left === count;
  let threshold = countOnLeft ? comparison.right : comparison.left;
  while (ts.isParenthesizedExpression(threshold)) threshold = threshold.expression;
  if (!ts.isNumericLiteral(threshold)) return false;

  const operator = comparison.operatorToken.kind;
  const thresholds = EXISTENCE_THRESHOLDS.get(operator);
  const expected = ZERO_COMPARISONS.has(operator) ? 0 : thresholds?.[countOnLeft ? 'left' : 'right'];
  return Number(threshold.text) === expected && hasOnlyOptions(call, COUNT_OPTIONS);
}

function projectsField(call, field) {
  if (!hasOnlyOptions(call, FILTER_SORT_OPTIONS)) return false;
  const selection = call.arguments[0]?.properties.find((property) => property.name.text === 'select');
  if (!selection) return true;
  if (!ts.isPropertyAssignment(selection) || !ts.isObjectLiteralExpression(selection.initializer)) return false;
  return (
    selection.initializer.properties.every(
      (property) =>
        ts.isPropertyAssignment(property) && (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)),
    ) &&
    selection.initializer.properties.some(
      (property) => property.name.text === field && property.initializer.kind === ts.SyntaxKind.TrueKeyword,
    )
  );
}

function repeatedOperationAdvice(operation) {
  if (SINGLE_ROW_WRITES.has(operation)) {
    return 'Use `createMany`, `updateMany` or `deleteMany` with an `in` filter if validation, ordering and transaction semantics allow it.';
  }
  if (operation.startsWith('findUnique')) {
    return 'Prisma may batch same-tick findUnique calls, but a single `findMany({ where: { id: { in: ids } } })` guarantees one query.';
  }
  return 'Fetch all keys in one query, for example `findMany({ where: { id: { in: ids } } })`, or use `include`/`groupBy`, then index the rows in a Map.';
}

function checkPrismaCall(call, context) {
  const access = call.expression;
  if (!ts.isPropertyAccessExpression(access)) return;
  const operation = access.name.text;
  if (!READ_OPERATIONS.has(operation) && !SINGLE_ROW_WRITES.has(operation)) return;

  const awaited = operation === 'findMany' && awaitedResult(call);
  const readsCount = awaited && readsResultLength(awaited) && hasOnlyOptions(call, COUNT_OPTIONS);
  const readsFirst = awaited && firstElementRead(awaited) && hasOnlyOptions(call, FIRST_OPTIONS);
  const testsExistence = operation === 'count' && countForExistence(call);
  const clientSide = awaited && clientSideQuery(awaited);
  const canPushDown = clientSide && projectsField(call, clientSide.field);
  const repeatOwner = findRepeatOwner(call, context.checker);
  // Same-tick findUnique calls can share Prisma's dataloader. A sequential await in a loop cannot.
  const mayBatch =
    operation.startsWith('findUnique') && repeatOwner && (ts.isFunctionLike(repeatOwner) || !awaitedResult(call));
  const inLoop = repeatOwner && !mayBatch && consumesPrismaQuery(call, context.checker);
  if (!readsCount && !readsFirst && !testsExistence && !canPushDown && !inLoop) return;

  if (!prismaModelName(access.name, context.checker)) return;

  if (readsCount) {
    context.report(
      access.name,
      'prisma-count-materialization',
      'findMany() loads every matching row only to read its length. Use `prisma.model.count({ where })` with the same filter.',
    );
  }
  if (testsExistence) {
    context.report(
      access.name,
      'prisma-count-for-existence',
      'This count() comparison only checks whether any row exists. Use `findFirst` on the same delegate with the same `where` and a small scalar projection, then check whether the result is null.',
    );
  }
  if (readsFirst) {
    context.report(
      access.name,
      'prisma-first-materialization',
      'findMany() loads every matching row but only the first is read. Use `findFirst({ where, orderBy, select })` with a deterministic orderBy; it returns null (not undefined) when empty.',
    );
  }
  if (canPushDown) {
    if (clientSide.method.text === 'filter') {
      context.report(
        clientSide.method,
        'prisma-filter-materialization',
        'findMany() loads rows that JavaScript then filters by one field. Move the test into the query with `where: { AND: [where, { field: value }] }`; check NULL handling and comparison semantics.',
      );
    } else {
      context.report(
        clientSide.method,
        'prisma-top-k-materialization',
        "findMany() loads all rows that JavaScript then sorts and truncates. Use `orderBy: { field: 'desc' }, take: limit` in the query; keep NULL ordering and tie behavior.",
      );
    }
  }
  if (
    inLoop &&
    !isSequentialByDesign(call, repeatOwner) &&
    shouldReportLoopQuery(call, context.checker, { family: 'Prisma', method: operation, owner: repeatOwner })
  ) {
    context.report(
      access.name,
      'prisma-query-in-loop',
      `Prisma ${operation}() runs once per iteration, adding a round trip per item. ${repeatedOperationAdvice(operation)}`,
    );
  }
}

function isPrismaClientMember(name, checker) {
  return !!checker
    .getSymbolAtLocation(name)
    ?.declarations?.some(
      (declaration) =>
        PRISMA_PACKAGE_PATH.test(declaration.getSourceFile().fileName.replaceAll('\\', '/')) ||
        isGeneratedPrismaFile(declaration.getSourceFile()),
    );
}

// Raw statements are tagged templates such as tx.$executeRaw`...`, not calls, so checkPrismaCall never sees them.
function checkPrismaRawTemplate(node, context) {
  const tag = node.tag;
  if (!ts.isPropertyAccessExpression(tag) || !RAW_TEMPLATE_TAGS.has(tag.name.text)) return;
  const owner = findRepeatOwner(node, context.checker);
  if (!owner || !consumesLazyQuery(node, context.checker) || !isPrismaClientMember(tag.name, context.checker)) return;
  if (isSequentialByDesign(node, owner) || !shouldReportLoopQuery(node, context.checker, { owner })) return;
  context.report(
    tag.name,
    'prisma-query-in-loop',
    `Prisma ${tag.name.text} runs one raw statement per iteration, adding a round trip per item. Send one set-based statement for all items, for example \`WHERE id = ANY(\${ids})\` or \`UPDATE ... FROM (VALUES ...)\`, if per-row values, ordering and results allow it.`,
  );
}

