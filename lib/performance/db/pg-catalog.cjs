const minimumGenericPlanVersion = 160_000;

// quote_ident semantics, applied unconditionally: always quoted, embedded quotes doubled.
function quoteIdent(identifier) {
  if (typeof identifier !== 'string' || identifier === '' || identifier.includes('\0')) {
    throw new TypeError('Invalid identifier.');
  }
  return '"' + identifier.replaceAll('"', '""') + '"';
}

// Builds CREATE INDEX from catalog identifiers only; `name` is omitted for HypoPG, which names its own.
function indexDefinition({ schema, table, columns, name }) {
  if (!Array.isArray(columns) || columns.length === 0) throw new TypeError('An index needs at least one column.');
  const named = name ? ' ' + quoteIdent(name) : '';
  return `CREATE INDEX${named} ON ${quoteIdent(schema)}.${quoteIdent(table)} (${columns.map(quoteIdent).join(', ')})`;
}

