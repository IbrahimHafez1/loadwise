const { syntax: ts } = require('./compiler.cjs');
const {
  awaitedResult,
  chainedMethod,
  clientSideQuery,
  consumesLazyQuery,
  firstElementRead,
  isDiscardedValue,
  outsideWrappers,
} = require('./query-results.cjs');
const { findRepeatOwner } = require('./repeated.cjs');
const { shouldReportLoopQuery } = require('./query-loops.cjs');
const { isSequentialByDesign } = require('./sequential-loops.cjs');

const READ_OPERATIONS = new Set([
  'findUnique',
  'findUniqueOrThrow',
  'findFirst',
  'findFirstOrThrow',
  'findMany',
  'count',
  'aggregate',
  'groupBy',
]);
const SINGLE_ROW_WRITES = new Set(['create', 'update', 'delete', 'upsert']);
const promiseMethods = new Set(['then', 'catch', 'finally']);
const COUNT_OPTIONS = new Set(['where']);
const FIRST_OPTIONS = new Set(['where', 'orderBy', 'select', 'include', 'omit']);
const FILTER_SORT_OPTIONS = new Set(['where', 'orderBy', 'select']);
const PRISMA_PACKAGE_PATH = /\/node_modules\/(?:@prisma\/client|\.prisma\/client)\//;
const generatedFiles = new WeakMap();

function isGeneratedPrismaFile(file) {
  if (!generatedFiles.has(file)) {
    // The modern generator emits each model into the application's own directory.
    const fromPackage = PRISMA_PACKAGE_PATH.test(file.fileName.replaceAll('\\', '/'));
    const fromGenerator =
      !fromPackage &&
      file.statements.length > 0 &&
      file.text.slice(0, file.statements[0].getStart(file)).includes('This is code generated by Prisma') &&
      file.statements.some(
        (statement) =>
          ts.isImportDeclaration(statement) &&
          ts.isStringLiteral(statement.moduleSpecifier) &&
          statement.moduleSpecifier.text.startsWith('@prisma/client/runtime/'),
      );
    generatedFiles.set(file, fromPackage || fromGenerator);
  }
  return generatedFiles.get(file);
}

function consumesPrismaQuery(call, checker) {
  return consumesLazyQuery(call, checker) || promiseMethods.has(chainedMethod(call)?.expression.name.text);
}

function delegateName(owner) {
  if (
    ts.isInterfaceDeclaration(owner) &&
    owner.name.text.endsWith('Delegate') &&
    isGeneratedPrismaFile(owner.getSourceFile())
  ) {
    return owner.name.text.slice(0, -'Delegate'.length);
  }
}

function prismaModelName(methodName, checker) {
  const declarations = checker.getSymbolAtLocation(methodName)?.declarations;
  if (declarations?.length && declarations.every((declaration) => declaration.parent === declarations[0].parent)) {
    return delegateName(declarations[0].parent);
  }
}

function prismaModelNameFromReceiver(receiver, checker) {
  const declarations = checker.getTypeAtLocation(receiver).getSymbol()?.declarations;
  if (declarations?.length === 1) return delegateName(declarations[0]);
}

function readsResultLength(awaited) {
  const receiver = outsideWrappers(awaited);
  const access = receiver.parent;
  return (
    ts.isPropertyAccessExpression(access) &&
    access.expression === receiver &&
    access.name.text === 'length' &&
    !ts.isAssignmentTarget(access) &&
    !ts.isDeleteExpression(outsideWrappers(access).parent) &&
    !isDiscardedValue(access)
  );
}

function hasOnlyOptions(call, allowed) {
  if (call.arguments.length === 0) return true;
  const [options] = call.arguments;
  return (
    call.arguments.length === 1 &&
    ts.isObjectLiteralExpression(options) &&
    options.properties.every(
      (property) =>
        (ts.isPropertyAssignment(property) || ts.isShorthandPropertyAssignment(property)) &&
        (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
        allowed.has(property.name.text),
    )
  );
}

function projectsField(call, field) {
  if (!hasOnlyOptions(call, FILTER_SORT_OPTIONS)) return false;
  const selection = call.arguments[0]?.properties.find((property) => property.name.text === 'select');
  if (!selection) return true;
  if (!ts.isPropertyAssignment(selection) || !ts.isObjectLiteralExpression(selection.initializer)) return false;
  return (
    selection.initializer.properties.every(
      (property) =>
        ts.isPropertyAssignment(property) && (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)),
    ) &&
    selection.initializer.properties.some(
      (property) => property.name.text === field && property.initializer.kind === ts.SyntaxKind.TrueKeyword,
    )
  );
}

function repeatedOperationAdvice(operation) {
  if (SINGLE_ROW_WRITES.has(operation)) {
    return 'Use `createMany`, `updateMany` or `deleteMany` with an `in` filter if validation, ordering and transaction semantics allow it.';
  }
  if (operation.startsWith('findUnique')) {
    return 'Prisma may batch same-tick findUnique calls, but a single `findMany({ where: { id: { in: ids } } })` guarantees one query.';
  }
  return 'Fetch all keys in one query, for example `findMany({ where: { id: { in: ids } } })`, or use `include`/`groupBy`, then index the rows in a Map.';
}

function checkPrismaCall(call, context) {
  const access = call.expression;
  if (!ts.isPropertyAccessExpression(access)) return;
  const operation = access.name.text;
  if (!READ_OPERATIONS.has(operation) && !SINGLE_ROW_WRITES.has(operation)) return;

  const awaited = operation === 'findMany' && awaitedResult(call);
  const readsCount = awaited && readsResultLength(awaited) && hasOnlyOptions(call, COUNT_OPTIONS);
  const readsFirst = awaited && firstElementRead(awaited) && hasOnlyOptions(call, FIRST_OPTIONS);
  const clientSide = awaited && clientSideQuery(awaited);
  const canPushDown = clientSide && projectsField(call, clientSide.field);
  const repeatOwner = findRepeatOwner(call, context.checker);
  // Same-tick findUnique calls can share Prisma's dataloader. A sequential await in a loop cannot.
  const mayBatch =
    operation.startsWith('findUnique') && repeatOwner && (ts.isFunctionLike(repeatOwner) || !awaitedResult(call));
  const inLoop = repeatOwner && !mayBatch && consumesPrismaQuery(call, context.checker);
  if (!readsCount && !readsFirst && !canPushDown && !inLoop) return;

  if (!prismaModelName(access.name, context.checker)) return;

  if (readsCount) {
    context.report(
      access.name,
      'prisma-count-materialization',
      'findMany() loads every matching row only to read its length. Use `prisma.model.count({ where })` with the same filter.',
    );
  }
  if (readsFirst) {
    context.report(
      access.name,
      'prisma-first-materialization',
      'findMany() loads every matching row but only the first is read. Use `findFirst({ where, orderBy, select })` with a deterministic orderBy; it returns null (not undefined) when empty.',
    );
  }
  if (canPushDown) {
    if (clientSide.method.text === 'filter') {
      context.report(
        clientSide.method,
        'prisma-filter-materialization',
        'findMany() loads rows that JavaScript then filters by one field. Move the test into the query with `where: { AND: [where, { field: value }] }`; check NULL handling and comparison semantics.',
      );
    } else {
      context.report(
        clientSide.method,
        'prisma-top-k-materialization',
        "findMany() loads all rows that JavaScript then sorts and truncates. Use `orderBy: { field: 'desc' }, take: limit` in the query; keep NULL ordering and tie behavior.",
      );
    }
  }
  if (
    inLoop &&
    !isSequentialByDesign(call, repeatOwner) &&
    shouldReportLoopQuery(call, context.checker, { family: 'Prisma', method: operation, owner: repeatOwner })
  ) {
    context.report(
      access.name,
      'prisma-query-in-loop',
      `Prisma ${operation}() runs once per iteration, adding a round trip per item. ${repeatedOperationAdvice(operation)}`,
    );
  }
}

module.exports = {
  checkPrismaCall,
  consumesPrismaQuery,
  isGeneratedPrismaFile,
  prismaModelName,
  prismaModelNameFromReceiver,
};
