'use strict';

const ts = require('typescript');

const minimumStatements = 3;
const minimumBodyNodes = 30;
const maximumBodyNodes = 8192;
// Outside the range of any syntax kind character, so it cannot read as a node kind.
const optionalLinkMarker = String.fromCharCode(0xffff);
const maximumKeyLength = 128 * 1024;
const minifiedLineLength = 2000;
const minifiedStatementCount = 50;
const generatedName = /(?:^|\/)(?:__generated__|generated)\/|(?:^|\.)(?:generated|gen)\.[cm]?[jt]sx?$|\.min\.js$/i;
// Standalone demo apps, fixtures, seed data and migrations are copied on purpose and cannot share code with the main
// app. Per-release folders such as upgrade-commands/2-34/ freeze each release's code the same way migrations do.
const standaloneCopyDirectory =
  /(?:^|\/)(?:(?:samples?|examples?|fixtures?|__fixtures__|integration|migrations?|(?:[\w-]+-)?seed(?:s|ers?)?)\/|v?\d+[-._]\d+(?:[-._]\d+)*\/)/i;
const testFile = /(?:^|\/)(?:tests?|__tests__|spec)\/|\.(?:test|spec)\.[cm]?[jt]sx?$/i;
const generatedComment =
  /(?:^|\n)\s*[/\s*]*(?:@generated\b|(?:(?:this (?:file|code) (?:is|was)|code)\s+)?(?:auto[- ]?generated\b|generated by\b|generated from\b[^\n]*\bdo not edit\b))/i;

// One reused buffer with a static callback avoids allocating per node. Callers copy the children out
// before visiting anything else.
const childBuffer = [];
let childCount = 0;
function bufferChild(child) {
  childBuffer[childCount++] = child;
}

// Buffers the node's children in forEachChild order and returns how many there are.
function bufferChildren(node) {
  childCount = 0;
  ts.forEachChild(node, bufferChild);
  return childCount;
}

function countStatementSeparators(text, start, end) {
  let count = 0;
  for (let index = text.indexOf(';', start); index !== -1 && index < end; index = text.indexOf(';', index + 1)) count++;
  return count;
}

// Bundler and minifier output packs many statements onto one long line. A long expression or data literal written
// on one line is still a single statement, so it does not count.
function minifiedText(text) {
  let lineStart = 0;
  while (lineStart < text.length) {
    const lineEnd = text.indexOf('\n', lineStart);
    const end = lineEnd === -1 ? text.length : lineEnd;
    if (
      end - lineStart > minifiedLineLength &&
      countStatementSeparators(text, lineStart, end) >= minifiedStatementCount
    )
      return true;
    lineStart = end + 1;
  }
  return false;
}

function generatedSource(file, path) {
  if (file.isDeclarationFile || generatedName.test(path) || minifiedText(file.text)) return true;
  const header = file.text.slice(0, 2048);
  return ts
    .getLeadingCommentRanges(header, 0)
    ?.some((range) => generatedComment.test(header.slice(range.pos, range.end)));
}

function documentsReferenceCopy(file, relativePath) {
  if (!testFile.test(relativePath)) return false;
  // Test oracles may deliberately retain the previous implementation for comparison.
  // Only consider introductory comments before the first implementation statement.
  const comments = [];
  for (const statement of file.statements) {
    for (const range of ts.getLeadingCommentRanges(file.text, statement.pos) ?? []) {
      comments.push(file.text.slice(range.pos, range.end).replace(/[/\s*]+/g, ' '));
    }
    if (!ts.isImportDeclaration(statement) && !ts.isImportEqualsDeclaration(statement)) break;
  }
  const description = comments.join(' ');
  return (
    (/\b(?:kept|copied|retained|preserved)\s+(?:(?:here|intentionally|deliberately)\s+)*verbatim\b/i.test(
      description,
    ) &&
      /\b(?:compare[ds]?|comparison|equivalence|parity|oracle)\b/i.test(description)) ||
    /\b(?:independent (?:test oracle|reference implementation)|test oracle independent of (?:the )?implementation)\b/i.test(
      description,
    )
  );
}

function functionName(node, parent) {
  if (ts.isFunctionDeclaration(node) || ts.isMethodDeclaration(node) || (ts.isFunctionExpression(node) && node.name)) {
    return node.name;
  }
  if (
    (ts.isArrowFunction(node) || ts.isFunctionExpression(node)) &&
    parent &&
    (ts.isVariableDeclaration(parent) || ts.isPropertyAssignment(parent) || ts.isPropertyDeclaration(parent))
  ) {
    return parent.name;
  }
}

function qualifies(body) {
  if (
    body.statements.length === 0 ||
    (body.statements.length < minimumStatements &&
      body.statements.every(
        (statement) =>
          ts.isReturnStatement(statement) ||
          ts.isExpressionStatement(statement) ||
          ts.isVariableStatement(statement) ||
          ts.isThrowStatement(statement),
      ))
  )
    return false;
  let nodes = 0;
  let statements = 0;
  let operations = 0;
  let controlFlow = false;
  let hasLocalValue = false;
  // Long operator chains nest thousands deep, so the walk below uses an explicit stack instead of recursion.
  // Returns true when the body is too large or contains a nested block implementation.
  function rejects(node) {
    // Nested block implementations are visited independently, avoiding overlapping reports and repeated subtree walks.
    if (++nodes > maximumBodyNodes || (node !== body && ts.isFunctionLike(node) && node.body && ts.isBlock(node.body)))
      return true;
    if (ts.isStatement(node) && !ts.isBlock(node) && !ts.isEmptyStatement(node)) statements++;
    if (
      ts.isCallExpression(node) ||
      ts.isNewExpression(node) ||
      ts.isBinaryExpression(node) ||
      ts.isAwaitExpression(node)
    )
      operations++;
    if (
      ts.isIfStatement(node) ||
      ts.isIterationStatement(node, false) ||
      ts.isSwitchStatement(node) ||
      ts.isTryStatement(node) ||
      ts.isConditionalExpression(node)
    )
      controlFlow = true;
    if (ts.isVariableDeclaration(node) && node.initializer) hasLocalValue = true;
    return false;
  }
  const pending = [body];
  while (pending.length) {
    const node = pending.pop();
    if (rejects(node)) return false;
    for (let index = bufferChildren(node) - 1; index >= 0; index--) pending.push(childBuffer[index]);
  }
  return (
    nodes >= minimumBodyNodes && statements >= minimumStatements && operations >= 2 && (controlFlow || hasLocalValue)
  );
}

// `value!.member` and `value?.member` are one chain for grouping: the non-null assertion is a type-level claim that
// an author wrote in place of the optional chain, so the two spellings count as the same copy.
function isChainOperand(node) {
  const parent = node.parent;
  return (
    ts.isNonNullExpression(node) &&
    (ts.isPropertyAccessExpression(parent) || ts.isElementAccessExpression(parent) || ts.isCallExpression(parent)) &&
    parent.expression === node
  );
}

// A block that is the body of if/else or a loop and holds one statement means that statement. Function bodies, and
// blocks that declare block-scoped names, keep their block because removing it would change scope.
function isRedundantBlock(node) {
  if (!ts.isBlock(node) || node.statements.length !== 1) return false;
  const parent = node.parent;
  const controlled =
    (ts.isIfStatement(parent) && (parent.thenStatement === node || parent.elseStatement === node)) ||
    (ts.isIterationStatement(parent, false) && parent.statement === node);
  const [statement] = node.statements;
  const scoped =
    ts.isClassDeclaration(statement) ||
    ts.isFunctionDeclaration(statement) ||
    (ts.isVariableStatement(statement) && Boolean(statement.declarationList.flags & ts.NodeFlags.BlockScoped));
  return controlled && !scoped;
}

function isOptionalLink(node) {
  const isChain =
    ts.isPropertyAccessExpression(node) || ts.isElementAccessExpression(node) || ts.isCallExpression(node);
  return isChain && Boolean(node.questionDotToken || isChainOperand(node.expression));
}

// The dot and the question-dot are folded into the optional-link marker written for the access node.
function foldedChainToken(node) {
  return (
    node.kind === ts.SyntaxKind.QuestionDotToken ||
    (node.kind === ts.SyntaxKind.DotToken && ts.isPropertyAccessExpression(node.parent))
  );
}

function canonicalKey(fn, file) {
  const parts = [
    fn.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.AsyncKeyword) ? 'a' : 's',
    fn.asteriskToken ? '*' : '.',
  ];
  let length = 0;
  // Returns false once the key would exceed its size limit.
  function encodeNode(node) {
    // Real parser tokens preserve regex, JSX, template text and automatic semicolon insertion.
    // AST boundaries distinguish bodies with equal token spellings and different statement grouping.
    const kind = String.fromCharCode(node.kind + 1);
    let token = '';
    if (foldedChainToken(node)) return true;
    if (node.kind <= ts.SyntaxKind.LastToken) {
      if (
        node.kind === ts.SyntaxKind.Identifier ||
        node.kind === ts.SyntaxKind.PrivateIdentifier ||
        ts.isLiteralExpression(node) ||
        ts.isTemplateLiteralToken(node) ||
        node.kind === ts.SyntaxKind.JsxText ||
        node.kind === ts.SyntaxKind.JsxTextAllWhiteSpaces
      ) {
        const jsxText = node.kind === ts.SyntaxKind.JsxText || node.kind === ts.SyntaxKind.JsxTextAllWhiteSpaces;
        const start = jsxText ? node.pos : node.getStart(file);
        if (node.end - start > maximumKeyLength) return false;
        const spelling = file.text.slice(start, node.end);
        token = String(spelling.length) + ':' + spelling;
      }
      length += 1 + token.length;
      if (length > maximumKeyLength) return false;
      parts.push(kind, token);
      return true;
    }
    length += 2;
    if (length > maximumKeyLength) return false;
    parts.push(kind);
    if (isOptionalLink(node)) {
      length += 1;
      parts.push(optionalLinkMarker);
    }
    return true;
  }
  // An explicit stack keeps long operator chains off the call stack. A null entry closes its enclosing node.
  function encode(root) {
    const pending = [root];
    while (pending.length) {
      const node = pending.pop();
      if (node === null) {
        parts.push('\0');
        continue;
      }
      if (isChainOperand(node)) {
        pending.push(node.expression);
        continue;
      }
      if (isRedundantBlock(node)) {
        pending.push(node.statements[0]);
        continue;
      }
      if (!encodeNode(node)) return false;
      if (node.kind <= ts.SyntaxKind.LastToken) continue;
      pending.push(null);
      const children = node.getChildren(file);
      for (let index = children.length - 1; index >= 0; index--) pending.push(children[index]);
    }
    return true;
  }
  for (const parameter of fn.parameters) if (!encode(parameter)) return;
  if (encode(fn.body)) return parts.join('');
}

function compareLocations(first, second) {
  return first.file < second.file
    ? -1
    : first.file > second.file
      ? 1
      : first.line - second.line || first.column - second.column;
}

// Reads one parsed file into plain data (safe to send between threads); undefined for files that are never compared.
function extractImplementations(file, relativePath) {
  if (standaloneCopyDirectory.test(relativePath) || generatedSource(file, relativePath)) return;
  const implementations = [];
  const testSource = testFile.test(relativePath);
  function visit(node, parent, insideFunction, pending) {
    // Closures declared inside a test callback are that test's own setup, not shared production logic.
    if (ts.isFunctionLike(node) && node.body && ts.isBlock(node.body) && !(testSource && insideFunction)) {
      const name = functionName(node, parent);
      if (name && qualifies(node.body)) {
        const key = canonicalKey(node, file);
        if (key) {
          const position = file.getLineAndCharacterOfPosition(name.getStart(file));
          implementations.push({ key, line: position.line + 1, column: position.character + 1 });
        }
      }
    }
    const inside = insideFunction || ts.isFunctionLike(node);
    for (let index = bufferChildren(node) - 1; index >= 0; index--) {
      const child = childBuffer[index];
      // Tokens have no children and are never implementations, so skipping them keeps the walk cheap.
      if (child.kind > ts.SyntaxKind.LastToken) pending.push(child, node, inside);
    }
  }
  // Each node travels with its parent on an explicit stack, so long operator chains never exhaust the call stack.
  const pending = [file, undefined, false];
  while (pending.length) {
    const insideFunction = pending.pop();
    const parent = pending.pop();
    visit(pending.pop(), parent, insideFunction, pending);
  }
  return { implementations, documentsReference: documentsReferenceCopy(file, relativePath) };
}

function createDuplicateIndex() {
  // Map uses hashed lookup plus complete string equality, including on hash collisions.
  // Retain one compact key per distinct implementation. SourceFiles and syntax nodes can be collected after add().
  const groups = new Map();
  const scanned = new Set();
  const references = new Set();
  function addExtracted(relativePath, extracted) {
    if (!extracted || scanned.has(relativePath)) return;
    scanned.add(relativePath);
    if (extracted.documentsReference) references.add(relativePath);
    for (const { key, line, column } of extracted.implementations) {
      const location = { file: relativePath, line, column };
      const group = groups.get(key);
      if (group) group.push(location);
      else groups.set(key, [location]);
    }
  }
  return {
    addExtracted,
    add(file, relativePath) {
      if (!scanned.has(relativePath)) addExtracted(relativePath, extractImplementations(file, relativePath));
    },
    findings() {
      const findings = [];
      for (const locations of groups.values()) {
        if (locations.length < 2) continue;
        const [first, ...related] = locations.slice().sort(compareLocations);
        const finding = {
          ...first,
          ruleId: 'duplicate-implementation',
          message: `These ${locations.length} functions have identical implementation syntax. If they implement the same contract, extract one shared function, call it from each listed location, and test it once. Changes to one copy will otherwise miss the others. Compare input, error and boundary behavior first, since similar-looking copies can differ on purpose.`,
          related,
        };
        if (locations.filter((site) => !references.has(site.file)).length === 1) {
          finding.contextualReason =
            'The other implementations belong to tests that explicitly document an independent comparison copy.';
        }
        findings.push(finding);
      }
      return findings.sort(compareLocations);
    },
  };
}

module.exports = { canonicalKey, createDuplicateIndex, extractImplementations, generatedSource, testFile };
